import argparse,hashlib,json,pathlib,xml.etree.ElementTree as ET,zipfile
ROOT=pathlib.Path(__file__).resolve().parents[1]
JAR_SHA='9b35257edea808ec80a8bcd48882d174b107152d9640b5ca33e1365593cff2a5'
def sha(b):return hashlib.sha256(b).hexdigest()
def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--jar',type=pathlib.Path,required=True);a=p.parse_args();assert sha(a.jar.read_bytes())==JAR_SHA
 fixture=ROOT/'fixtures/official-head-staff-catalog';metadata=json.loads((fixture/'controls.json').read_text())['shape_sets']
 with zipfile.ZipFile(a.jar) as z:xml=z.read('res/drum-set.xml')
 (fixture/'original-drum-set.xml').write_bytes(xml)
 mappings={}
 for staff in ET.fromstring(xml).findall('staff'):
  n=int(staff.attrib['line-count'])
  for entry in staff.findall('entry'):
   if entry.attrib.get('sound') in (None,'null'):continue
   pitch=int(entry.attrib['pitch-position']);motif=entry.attrib['motif'];bit={'oval':1,'small':2,'cross':4,'diamond':8,'triangle':16,'circle':32}[motif]
   mappings[n,pitch]=mappings.get((n,pitch),0)|bit
 bits={'MATCHED':1,'STEM':2,'HOLLOW':4,'SMALL':8,'DRUM_ONLY':16,'CROSS':32}
 rows=['// SPDX-License-Identifier: AGPL-3.0-or-later','// Original ShapeSet enum order and default DrumSet mapping. Generated by', '// scripts/package_head_staff_catalog.py; no control-case lookups.',f'pub const DEFAULT_DRUM_MAP_SHA256: &str = "{sha(xml)}";']
 rows.extend('const '+name+': u32 = '+str(bit)+';' for name,bit in bits.items())
 rows.append('const HEAD_SHAPES: &[(&str, u32, u32)] = &[')
 for name in metadata['Heads']:
  flags=sum(bit for present,bit in [(name in metadata['HeadsOval'] or name in metadata['QuarterHeads'],1),(name in metadata['StemHeads'],2),(name in metadata['HollowHeads'],4),(name in metadata['HeadsOvalSmall'],8),(any(name in metadata[g] for g in ['HeadsDiamond','HeadsTriangle','HeadsCircle','HeadsCrossHollow']),16),(name in metadata['HeadsCross'],32)] if present)
  motif=sum(bit for group,bit in [('HeadsOval',1),('HeadsOvalSmall',2),('HeadsCross',4),('HeadsDiamond',8),('HeadsTriangle',16),('HeadsCircle',32)] if name in metadata[group])
  rows.append(f'    ("{name}", {flags}, {motif}),')
 rows.append('];');rows.append('const DRUM_MOTIFS: &[(usize, i32, u32)] = &[')
 rows.extend(f'    ({n}, {pitch}, {mask}),' for (n,pitch),mask in sorted(mappings.items()));rows.append('];')
 (ROOT/'src/head_staff_catalog_data.rs').write_text('\n'.join(rows)+'\n')
 (fixture/'catalog-build.json').write_text(json.dumps({'jar_sha256':JAR_SHA,'resource':'res/drum-set.xml','resource_sha256':sha(xml),'shape_sets_source':'original ShapeSet constants observed in enum order','head_shapes':len(metadata['Heads']),'drum_pitches':len(mappings),'custom_user_overrides':False},indent=2)+'\n')
 print(len(metadata['Heads']),'shape metadata rows;',len(mappings),'default drum pitch rows')
if __name__=='__main__':main()
